-- 🧭 Navigation

vim.keymap.set("n", "<leader>gg", "gg", {
    desc = "Go to top of file",
})

vim.keymap.set("n", "<leader>G", "G", {
    desc = "Go to bottom of file",
})

vim.keymap.set("n", "<leader>w", "w", {
    desc = "Next word",
})

vim.keymap.set("n", "<leader>b", "b", {
    desc = "Previous word",
})
